export type Flashcard = {
  id: string
  topic: string
  question: string
  answer: string
  source: { file: string; quote: string; page?: number }
}
export type Source = { file: string; name: string; type: string; size: number }
export type Course = {
  id: string
  title: string
  description?: string
  cards: Flashcard[]
  sources: Source[]
  errors: string[]
}
export type Progress = {
  classId: string
  cardId: string
  streak: number
  seen: number
  dueAt: string
  lastReviewedAt: string
}
export type Learner = { name: string; createdAt: string; progress: Progress[] }
export type SavedLearner = { name: string; token: string }

export async function request<T>(
  url: string,
  options: RequestInit = {},
  token?: string,
): Promise<T> {
  const response = await fetch(url, {
    ...options,
    headers: {
      'Content-Type': 'application/json',
      ...(token ? { Authorization: `Bearer ${token}` } : {}),
      ...options.headers,
    },
  })
  if (!response.ok) {
    const result = await response.json().catch(() => ({}))
    throw new Error(
      result.error || 'Unable to connect. Check your connection and try again.',
    )
  }
  return response.json()
}

export const coursePath = (id: string) => `/classes/${encodeURIComponent(id)}`
export const askPath = (classId: string, file?: string) =>
  `/ask?${new URLSearchParams({ class: classId, ...(file ? { file } : {}) })}`
export const sourcePath = (classId: string, file: string, cardId?: string) =>
  `${coursePath(classId)}/source?${new URLSearchParams({ file, ...(cardId ? { card: cardId } : {}) })}`
export const originalPath = (classId: string, file: string) =>
  `/api/source/${encodeURIComponent(classId)}?${new URLSearchParams({ file })}`
export const progressKey = (classId: string, cardId: string) =>
  JSON.stringify([classId, cardId])
